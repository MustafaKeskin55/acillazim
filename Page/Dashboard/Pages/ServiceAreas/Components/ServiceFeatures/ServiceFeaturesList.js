export const getFeaturesByCategory = (category) => {
  return SERVICE_FEATURES[category] || [];
};

export const getAllFeatures = () => {
  return Object.values(SERVICE_FEATURES).flat();
};

export const getCategories = () => {
  return Object.keys(SERVICE_FEATURES);
};

export const searchFeatures = (query) => {
  const searchTerm = query.toLowerCase();
  return getAllFeatures().filter(feature => 
    feature.title.toLowerCase().includes(searchTerm)
  );
};

export const getIconForTitle = (title) => {
  const titleLower = String(title || '').toLowerCase();
  const allFeatures = getAllFeatures();

  const exactMatch = allFeatures.find(
    (feature) => feature.title.toLowerCase() === titleLower
  );
  if (exactMatch) return exactMatch.icon;

  const partialMatch = allFeatures.find(
    (feature) =>
      titleLower.includes(feature.title.toLowerCase()) ||
      feature.title.toLowerCase().includes(titleLower)
  );
  if (partialMatch) return partialMatch.icon;

  return <FaTools color="#ffffff" />;
};
